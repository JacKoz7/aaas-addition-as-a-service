-- | The @traceparent@ of a gRPC request, if any.
--
-- __Description:__ Parsing keeps a valid @traceparent@ and ignores every
-- other custom metadata entry and an invalid value ('Nothing'), so a
-- caller's extra metadata never fails a call. Building sends the header
-- only for 'Just'.
--
-- __Business Justification:__ The trace of an addition continues through
-- @Next@ and @Propagate@ (CLAUDE.md 6.1).
--
-- __Owner:__ Arithmetic Excellence Center (AEC).
--
-- __Since:__ successor 0.2.0
newtype TraceMetadata = TraceMetadata (Maybe TraceContext)
  deriving stock (Eq, Show)

-- | The custom metadata name @traceparent@.
--
-- __Description:__ An ASCII header (no @-bin@ suffix), as in HTTP.
--
-- __Business Justification:__ One name for the server and the client.
--
-- __Owner:__ Arithmetic Excellence Center (AEC).
--
-- __Since:__ successor 0.2.0
--
-- >>> traceparentHeader
-- "traceparent"
traceparentHeader :: ByteString
traceparentHeader = "traceparent"

instance Default TraceMetadata where
  def = TraceMetadata Nothing

instance BuildMetadata TraceMetadata where
  buildMetadata (TraceMetadata context) =
    [CustomMetadata (AsciiHeader traceparentHeader) (TE.encodeUtf8 (renderTraceparent c)) | Just c <- [context]]

instance StaticMetadata TraceMetadata where
  metadataHeaderNames _ = [AsciiHeader traceparentHeader]

instance ParseMetadata TraceMetadata where
  parseMetadata entries =
    pure . TraceMetadata $
      case [value | CustomMetadata (AsciiHeader name) value <- entries, name == traceparentHeader] of
        value : _ -> either (const Nothing) parseTraceparent (TE.decodeUtf8' value)
        [] -> Nothing
